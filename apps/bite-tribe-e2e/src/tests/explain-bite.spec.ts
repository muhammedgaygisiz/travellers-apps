import { expect, Page, test } from '@playwright/test';
import { loginAsTestUser } from '../support/auth';
import { dismissCoachMarks } from '../support/coach-marks';
import {
  deleteFirestoreDocument,
  getFirestoreDocument,
  seedFirestoreDocument,
} from '../support/firestore';
import { completeOnboardingIfNeeded } from '../support/onboarding';
import { TEST_USERS } from '../support/test-users';

/** Another member's Bite, its photo in the given upload state. */
const seedBite = async (
  page: Page,
  biteId: string,
  name: string,
  imageStatus: 'uploaded' | 'pending',
): Promise<void> => {
  await seedFirestoreDocument(page, `bites/${biteId}`, {
    userId: { stringValue: TEST_USERS.fresh.uid },
    name: { stringValue: name },
    imageStatus: { stringValue: imageStatus },
    place: { stringValue: 'Explain Café' },
    city: { stringValue: 'Bangkok' },
    country: { stringValue: 'Thailand' },
    price: { stringValue: '3' },
    currency: { stringValue: 'THB' },
    createdAt: { stringValue: new Date().toISOString() },
    createdAtTimestamp: { integerValue: String(Date.now()) },
  });
};

/**
 * GitHub issue #2106: the AI explanation of a Bite's dish.
 *
 * Runs the real `explainBite` in the Functions emulator, which never calls the
 * model outside production and answers a `[DEV]` sample instead - so this
 * covers what the unit tests mock: the callable's auth and App Check path, the
 * explanation kept in Firestore, and the second open that reads it back
 * without counting against the member's day.
 */
test.describe('Explain a Bite', () => {
  test('explains the dish in a modal, and answers the second open from what was kept', async ({
    page,
  }) => {
    test.setTimeout(120_000);

    const runId = Date.now();
    const biteId = `explain-${runId}`;
    const dishName = `Som Tam ${runId}`;
    const usagePath = `aiUsage/${TEST_USERS.default.uid}`;

    // The day's count is durable emulator state: start it from nothing, so a
    // local re-run neither inherits nor exhausts an earlier run's allowance.
    await deleteFirestoreDocument(page, usagePath);
    await seedBite(page, biteId, dishName, 'uploaded');

    await loginAsTestUser(page);
    await completeOnboardingIfNeeded(page);
    await dismissCoachMarks(page);

    await page.goto(`/bite/${biteId}`);
    await dismissCoachMarks(page);

    const explain = page.getByTestId('bite-details-explain');
    const modal = page.locator('bt-bite-explanation');

    await explain.click();
    await expect(modal.getByTestId('bite-explanation-what')).toContainText(
      `[DEV] Sample explanation of ${dishName} in English.`,
    );
    await expect(modal).toContainText('Explained by AI');
    await expect(modal.getByTestId('bite-explanation-disclaimer')).toHaveText(
      'Generated by AI and may be inaccurate. Ask the restaurant about allergens.',
    );
    await expect(
      modal.getByTestId('bite-explanation-ingredients').locator('li'),
    ).toHaveCount(3);

    // Kept server-side, per Bite and language, with the name it was written for.
    expect(
      await getFirestoreDocument(page, `biteExplanations/${biteId}_en`),
    ).toMatchObject({ biteId, language: 'en', dishName, status: 'ok' });
    expect(await getFirestoreDocument(page, usagePath)).toMatchObject({
      explanations: 1,
    });

    await modal.getByTestId('bite-explanation-close').click();
    await expect(modal).toHaveCount(0);

    // The second open is answered from what was kept: the same text, and
    // nothing more counted against the day.
    await explain.click();
    await expect(modal.getByTestId('bite-explanation-what')).toContainText(
      dishName,
    );
    expect(await getFirestoreDocument(page, usagePath)).toMatchObject({
      explanations: 1,
    });

    await modal.getByTestId('bite-explanation-close').click();
    await deleteFirestoreDocument(page, `biteExplanations/${biteId}_en`);
    await deleteFirestoreDocument(page, `bites/${biteId}`);
  });

  test('is not offered while the Bite’s photo is still uploading', async ({
    page,
  }) => {
    const biteId = `explain-pending-${Date.now()}`;
    await seedBite(page, biteId, 'Pad Kra Pao', 'pending');

    await loginAsTestUser(page);
    await completeOnboardingIfNeeded(page);
    await dismissCoachMarks(page);

    await page.goto(`/bite/${biteId}`);
    await dismissCoachMarks(page);

    await expect(
      page
        .locator('details-page')
        .getByRole('heading', { name: 'Pad Kra Pao' }),
    ).toBeVisible();
    await expect(page.getByTestId('bite-details-explain')).toHaveCount(0);

    await deleteFirestoreDocument(page, `bites/${biteId}`);
  });
});

const businessRequest = (
  caller: Caller,
  data: Record<string, unknown>,
): never =>
  ({
    auth: { uid: caller.uid, token: { roles: caller.roles } },
    data,
  }) as never;

const guestRequest = (
  data: Record<string, unknown>,
  ip = GUEST_IP,
  uid = ALICE,
): never =>
  ({
    auth: {
      uid,
      token: { firebase: { sign_in_provider: 'anonymous' } },
    },
    data,
    rawRequest: { ip },
  }) as never;

/**
 * One resolution from an instance that has never seen this caller.
 *
 * The memory counter is emptied first, which is what a distributed loop looks
 * like from the durable counter's side: thirty requests per instance is under
 * the free limit, so every one of them reaches Firestore. Without the reset
 * these tests would be measuring the in-memory gate.
 */
const scanFromFreshInstance = (
  token = TOKEN,
  now = LUNCHTIME,
  ip = GUEST_IP,
): Promise<TableScanResult> => {
  resetScanRateLimit();

  return resolveTableQrTokenHandler(guestRequest({ token }, ip), now);
};

const start = (
  data: Record<string, unknown> = { token: TOKEN },
  now = LUNCHTIME,
  uid = ALICE,
): Promise<StartTableSessionResult> => {
  resetScanRateLimit();

  return startTableSessionHandler(guestRequest(data, GUEST_IP, uid), now);
};

const rotateBulk = (
  caller: Caller,
  data: Record<string, unknown>,
): Promise<RotateTableQrTokensResult> =>
  rotateTableQrTokensHandler(businessRequest(caller, data));

const dismiss = (
  caller: Caller,
  tableId: string,
  kind: ScanAnomalyKind,
): Promise<DismissScanAnomalyResult> =>
  dismissScanAnomalyHandler(
    businessRequest(caller, { restaurantId: RESTAURANT, tableId, kind }),
  );

const restaurantRef = (): DocumentReference =>
  getFirestore().collection('restaurants').doc(RESTAURANT);

const readAnomaly = async (
  tableId: string,
  kind: ScanAnomalyKind,
): Promise<DocumentData | undefined> =>
  (
    await restaurantRef()
      .collection(SCAN_ANOMALIES_COLLECTION)
      .doc(scanAnomalyId(tableId, kind))
      .get()
  ).data();

const readAnomalies = async (): Promise<DocumentData[]> =>
  (await restaurantRef().collection(SCAN_ANOMALIES_COLLECTION).get()).docs.map(
    (anomaly) => anomaly.data(),
  );

const readToken = async (token: string): Promise<DocumentData | undefined> =>
  (
    await getFirestore().collection(TABLE_TOKENS_COLLECTION).doc(token).get()
  ).data();

const readTable = async (tableId: string): Promise<DocumentData> =>
  (await restaurantRef().collection('tables').doc(tableId).get()).data() ?? {};

/** Puts a counter at the limit, so the next real scan is the one that crosses. */
const fillCounter = (
  dimension: 'token' | 'client' | 'ip',
  value: string,
  count: number,
  now = LUNCHTIME,
): Promise<unknown> => {
  const windowStartedAt = windowStartOf(now.getTime());

  return getFirestore()
    .collection(SCAN_RATE_LIMITS_COLLECTION)
    .doc(`${dimension}_${bucketOf(dimension, value)}_${windowStartedAt}`)
    .set({ dimension, windowStartedAt, count });
};

/** The error code an `HttpsError` carries, or the error itself if it is not one. */
const codeOf = async (call: Promise<unknown>): Promise<string> => {
  try {
    await call;
  } catch (error) {
    return (error as { code?: string }).code ?? String(error);
  }

  return 'no error';
};


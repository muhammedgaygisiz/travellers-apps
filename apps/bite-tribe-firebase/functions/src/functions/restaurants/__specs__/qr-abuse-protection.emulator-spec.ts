/**
 * The fixture tokens, and why each one is a pattern rather than a draw.
 *
 * A real token is 26 characters of Crockford base32 from the system CSPRNG,
 * which is indistinguishable from a leaked credential to any scanner that looks
 * at entropy - and this file would be committing three of them. So each fixture
 * is deliberately, visibly generated by hand: two alphabet runs and a row of
 * nines for the table numbered 99.
 *
 * They still have to be **valid**, because `normalizeScannedToken` refuses
 * anything that is not exactly 26 characters of `TOKEN_ALPHABET` before a
 * single read happens - so a token containing `I`, `L`, `O` or `U` would make
 * every test in this file pass for the wrong reason. Keep them patterned and
 * keep them legal; do not make one look more realistic.
 */
const TOKEN = 'ABCDEFGHJKMNPQRSTVWXYZ0123';
const TOKEN_TABLE_5 = '0123456789ABCDEFGHJKMNPQRS';
const TOKEN_RETIRED = '99999999999999999999999999';

const GUEST_IP = '203.0.113.7';


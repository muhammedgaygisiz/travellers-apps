import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

const REPO = 'https://github.com/muhammedgaygisiz/travellers-apps';
const releasesPath = resolve('ssot/releases');
const outputPath = resolve('ssot/releases/changelog.md');
const tags = getTags();

mkdirSync(releasesPath, { recursive: true });
clearReleasePages();
writeFileSync(outputPath, renderIndex(tags));

for (const release of buildReleases(tags)) {
  writeFileSync(
    join(releasesPath, getReleaseFileName(release.tag.name)),
    renderRelease(release),
  );
}

console.log(`Full changelog generated at ${outputPath}.`);

function getTags() {
  return git(['tag', '--sort=creatordate'])
    .split('\n')
    .map((tag) => tag.trim())
    .filter(Boolean)
    .map((name) => {
      const commit = git(['rev-list', '-n', '1', name]);
      const date = git(['log', '-1', '--format=%cs', commit]);

      return { commit, date, name };
    });
}

function clearReleasePages() {
  for (const entry of readdirSync(releasesPath, { withFileTypes: true })) {
    if (entry.isFile() && /^build-.+\.md$/.test(entry.name)) {
      rmSync(join(releasesPath, entry.name));
    }
  }
}

function getReleaseFileName(tagName) {
  return `${tagName}.md`;
}

function renderIndex(allTags) {
  const lines = [
    '# Changelog',
    '',
    'One page per release tag, oldest first. Generated by `npm run generate-full-changelog`',
    'from the git tags - change the generator in `tools/`, never these pages.',
    '',
    'Part of the [SSOT index](../README.md).',
    '',
  ];

  if (allTags.length === 0) {
    lines.push('No git tags found.');

    return `${lines.join('\n')}\n`;
  }

  lines.push(
    ...allTags.map((tag) => `- [${tag.name}](${getReleaseFileName(tag.name)}) (${tag.date})`),
  );

  return `${lines.join('\n')}\n`;
}

function buildReleases(allTags) {
  const releases = [];
  const previousTagCommits = [];

  for (const tag of allTags) {
    const commits = getCommitsForTag(tag.commit, previousTagCommits);

    releases.push({ commits, tag });
    previousTagCommits.push(tag.commit);
  }

  return releases;
}

function renderRelease({ commits, tag }) {
  const issues = new Set();
  const body =
    commits.length === 0
      ? ['No new commits since the previous tag.']
      : commits.map((commit) => renderCommit(commit, issues));

  const lines = [
    `# ${tag.name}`,
    '',
    '|             |                          |',
    '| ----------- | ------------------------ |',
    `| Date       | ${tag.date} |`,
    `| Git tag    | \`${tag.name}\` |`,
    `| Git commit | \`${tag.commit.slice(0, 8)}\` |`,
    '',
    'Part of the [changelog](changelog.md).',
    '',
    '## Commits',
    '',
    ...body,
  ];

  if (issues.size > 0) {
    lines.push(
      '',
      ...[...issues]
        .sort((left, right) => left - right)
        .map((number) => `[#${number}]: ${REPO}/issues/${number}`),
    );
  }

  return `${lines.join('\n')}\n`;
}

function getCommitsForTag(tagCommit, previousTagCommits) {
  const args = [
    'log',
    '--reverse',
    '--format=%h%x00%s',
    tagCommit,
    ...previousTagCommits.map((commit) => `^${commit}`),
  ];

  return git(args)
    .split('\n')
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => {
      const [hash, subject] = entry.split('\x00');

      return { hash, subject };
    });
}

function renderCommit(commit, issues) {
  return `- ${renderText(commit.subject, issues)} (\`${commit.hash}\`)`;
}

/** A bare #1234 does not link in a repository file, and opens a line it would be a heading. */
function renderText(value, issues) {
  return value.replace(/\s+/g, ' ').replace(/#(\d{1,5})\b/g, (_match, number) => {
    issues.add(Number(number));

    return `[#${number}]`;
  });
}

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8' }).trim();
}

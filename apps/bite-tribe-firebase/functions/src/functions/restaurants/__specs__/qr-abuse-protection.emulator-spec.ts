/**
 * QR token abuse protection against the real database (GitHub issue #1107).
 *
 * The emulator rather than a fake Firestore, for the reason every spec in this
 * folder gives: each claim the issue makes is about documents. That a durable
 * counter is shared across instances, that a flood produces one anomaly row
 * rather than a row per request, that a bulk rotation supersedes exactly the
 * codes of one room and leaves the rest of the building printed. A mocked store
 * would assert that the code called `set`, which was never the part in doubt.
 *
 * The rules half - that nobody may write an anomaly and nobody at all may read
 * a counter - is in `src/firestore-rules/__specs__`. The Admin SDK bypasses
 * rules, so it cannot be checked from here.
 *
 * ## Why the limit tests seed a counter instead of looping
 *
 * Reaching the durable token limit honestly is sixty-one resolutions, each of
 * them five document reads and six counter operations, in a spec that would
 * then be measuring the emulator rather than the rule. The counter documents
 * are addressed through this module's own `windowStartOf` and `bucketOf`, so a
 * seeded one is the same document the limiter would have written, and a change
 * to how the name is built fails these tests rather than quietly bypassing
 * them. The counting behaviour itself - that a refused attempt is still
 * counted, that a window rolls - is unit-tested in
 * `shared/utils/__specs__/scan-rate-limit.spec.ts` where it costs nothing.
 */
